<?php

declare(strict_types=1);

namespace App\Api;

use App\Api\Exceptions\EndpointDeclarationInvalid;
use App\Contracts\Domains\ApiPayload;
use App\Support\CallKey;
use App\Support\CodeFiles;
use App\Support\DeclaredType;
use App\Support\ReflectedMethod;
use App\Support\ReflectedParameter;
use App\Support\Reflector;
use Illuminate\Support\Str;
use UnitEnum;

/**
 * Writes the groups of the journal API: one group per Api folder, holding one method per payload that builds the
 * payload and sends it, and the JournalClient root holding Core's groups.
 */
final class ApiGroups
{
    /**
     * The widest line the generated code may hold.
     */
    private const int LINE_WIDTH = 120;

    /**
     * The group of one Api folder as PHP source, or null when the folder declares no payload; source is the folder
     * from the project root, which the group's AutoGenerated attribute names.
     *
     * @throws EndpointDeclarationInvalid
     */
    public static function group(string $folder, string $source, string $namespace, string $area): string|null
    {
        $payloads = self::payloadsIn($folder, $namespace);

        if ($payloads === []) {
            return null;
        }

        $methods = implode("\n", array_map(self::method(...), $payloads));
        $group = self::groupName($area);

        return <<<PHP
        <?php

        declare(strict_types=1);

        namespace {$namespace};

        use App\\Api\\Contracts\\Domains\\ApiSender;
        use App\\Attributes\\Generation\\AutoGenerated;
        use App\\Support\\CallKey;

        /**
         * The API of {$area}, generated by php artisan journal:api; run it again instead of editing.
         */
        #[AutoGenerated('{$source}')]
        final readonly class {$group}
        {
            public function __construct(private ApiSender \$sender) {}
        {$methods}}

        PHP;
    }

    /**
     * The JournalClient root over Core's groups, as PHP source.
     *
     * @param  array<string, class-string>  $groups  each Core area's group class, by area
     */
    public static function client(array $groups): string
    {
        $properties = implode('', array_map(
            fn (string $area, string $class) => "\n        public \\{$class} \$".Str::camel($area).',',
            array_keys($groups),
            $groups,
        ));

        $constructor = $groups === [] ? '' : <<<TEXT

            public function __construct({$properties}
            ) {}

        TEXT;

        return <<<PHP
        <?php

        declare(strict_types=1);

        namespace App\\Api;

        use App\\Attributes\\Generation\\AutoGenerated;

        /**
         * Every Core group of the journal API, generated by php artisan journal:api; run it again instead of editing.
         */
        #[AutoGenerated('app/Api')]
        final readonly class JournalClient
        {{$constructor}}

        PHP;
    }

    public static function groupName(string $area): string
    {
        return Str::singular($area).'Api';
    }

    /**
     * @return list<class-string>
     */
    private static function payloadsIn(string $folder, string $namespace): array
    {
        $payloads = [];

        $code = CodeFiles::ofProcess();

        foreach ($code->folder($code->projectPathOf("{$folder}/*Payload.php")) as $entry) {
            $class = $namespace.'\\'.basename($entry->name(), '.php');

            if (Reflector::factory()->isSubclassOf($class, ApiPayload::class)) {
                $payloads[] = $class;
            }
        }

        sort($payloads);

        return $payloads;
    }

    /**
     * @param  class-string  $payload
     *
     * @throws EndpointDeclarationInvalid
     */
    private static function method(string $payload): string
    {
        $endpoint = ApiDeclaration::of($payload)->endpoint;
        $declaration = Reflector::of($payload);
        $name = lcfirst(Str::beforeLast($declaration->shortName(), 'Payload'));

        $parameters = $declaration->constructor()
            ->map(fn (ReflectedMethod $constructor) => $constructor->parameters())
            ->getOrElse([]);

        $signature = implode('', array_map(
            fn (ReflectedParameter $parameter) => "\n        ".self::parameter($parameter).',',
            $parameters,
        ));

        $entries = array_map(
            fn (ReflectedParameter $parameter) => "'{$parameter->name()}' => \${$parameter->name()}",
            $parameters,
        );

        $oneLine = implode(', ', $entries);
        $sentLine = "        return \$this->sender->send({$declaration->shortName()}::from([{$oneLine}]));";

        // An argument array that fits its line stays on it; a longer one puts each entry on a line of its own.
        $parameterAssignments = strlen($sentLine) <= self::LINE_WIDTH
            ? $oneLine
            : implode('', array_map(fn (string $entry) => "\n            {$entry},", $entries))."\n        ";

        $answer = '\\'.$endpoint->answer;
        $docblock = self::docblock($declaration);

        return <<<PHP

        {$docblock}    public function {$name}({$signature}
            ): {$answer} {
                return \$this->sender->send(\\{$payload}::from([{$parameterAssignments}]));
            }

        PHP;
    }

    private static function parameter(ReflectedParameter $parameter): string
    {
        $declared = $parameter->type()->filter(fn (DeclaredType $type) => $type->isNamed());

        if ($declared->isEmpty()) {
            return "mixed \${$parameter->name()}";
        }

        $type = $declared->get();
        $nullable = $type->allowsNull && $type->name() !== 'mixed' ? '?' : '';
        $leading = $type->isBuiltin() ? '' : '\\';
        $written = $nullable.$leading.$type->name();
        $default = $type->name() === CallKey::class ? ' = new CallKey()' : self::defaultOf($parameter);

        return "{$written} \${$parameter->name()}{$default}";
    }

    /**
     * The default a payload's constructor gives the parameter, written as source; none when it has none.
     */
    private static function defaultOf(ReflectedParameter $parameter): string
    {
        if (! $parameter->hasDefaultValue()) {
            return '';
        }

        $constant = $parameter->defaultConstantName();

        if ($constant->isDefined()) {
            return ' = \\'.ltrim($constant->get(), '\\');
        }

        $defaultArgument = $parameter->defaultValue();

        return match (true) {
            $defaultArgument instanceof UnitEnum => ' = \\'.$defaultArgument::class.'::'.$defaultArgument->name,
            is_object($defaultArgument) => ' = new \\'.$defaultArgument::class.'()',
            default => ' = '.str_replace(["array (\n)", 'NULL'], ['[]', 'null'], var_export($defaultArgument, true)),
        };
    }

    /**
     * The array shapes the payload's constructor documents, so the group method types its arrays as the payload does;
     * a class named in a shape is written in full, since the group file does not share the payload's imports.
     *
     * @param  Reflector<object>  $call
     */
    private static function docblock(Reflector $call): string
    {
        $documented = $call->constructor()->flatMap(fn (ReflectedMethod $constructor) => $constructor->docComment());

        if ($documented->isEmpty()) {
            return '';
        }

        $constructorDoc = $documented->get();

        preg_match_all('/@param\s+(.+?)\s+(\$\w+)\s*$/m', $constructorDoc, $params, PREG_SET_ORDER);

        if ($params === []) {
            return '';
        }

        $imports = self::importsOf($call);

        $lines = array_map(
            fn (array $param) => '     * @param  '.self::fullyNamed($param[1], $imports, $call)."  {$param[2]}\n",
            $params,
        );

        return "/**\n".implode('', $lines)."     */\n";
    }

    /**
     * The classes the payload's file imports, by the short name it uses for each.
     *
     * @param  Reflector<object>  $call
     * @return array<string, string>
     */
    private static function importsOf(Reflector $call): array
    {
        $code = CodeFiles::ofProcess();

        preg_match_all(
            '/^use\s+([\w\\\\]+)(?:\s+as\s+(\w+))?;/m',
            $code->file($code->projectPathOf($call->fileName()->getOrElse(''))),
            $uses,
            PREG_SET_ORDER,
        );

        $imports = [];

        foreach ($uses as $use) {
            $imports[$use[2] ?? class_basename($use[1])] = $use[1];
        }

        return $imports;
    }

    /**
     * The type with every class name in it written in full: an imported name by its import, any other by the
     * payload's own namespace.
     *
     * @param  array<string, string>  $imports
     * @param  Reflector<object>  $call
     */
    private static function fullyNamed(string $type, array $imports, Reflector $call): string
    {
        return (string) preg_replace_callback(
            '/(?<![\w\\\\])[A-Z]\w*/',
            fn (array $name) => '\\'.($imports[$name[0]] ?? $call->namespaceName().'\\'.$name[0]),
            $type,
        );
    }
}
