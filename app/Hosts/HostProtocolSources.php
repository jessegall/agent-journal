<?php

declare(strict_types=1);

namespace App\Hosts;

use App\Hosts\Data\HostInstructionTraitsData;
use App\Hosts\Data\HostProtocolData;
use Illuminate\Support\Str;

/**
 * The Go and PHP source of host protocol 1, rendered from protocol/host.json, by each file's path from the project
 * root; journal:host-protocol writes them, and its check fails when one differs.
 */
final readonly class HostProtocolSources
{
    public const string PROTOCOL_FILE = 'protocol/host.json';

    private const string GENERATED = 'Generated by php artisan journal:host-protocol from protocol/host.json; '
        .'do not edit.';

    public function __construct(private HostProtocolData $protocol) {}

    /**
     * @return array<string, string>
     */
    public function sources(): array
    {
        $go = new GoProtocolSources($this->protocol);

        return [
            'app/Hosts/Protocol/HostInstructionType.php' => $this->instructionTypeEnum(),
            'app/Hosts/Protocol/HostRefusal.php' => $this->refusalEnum(),
            'app/Hosts/Protocol/HostProtocolVersion.php' => $this->versionClass(),
            'app/Hosts/Protocol/HostPlaceholders.php' => $this->placeholdersClass(),
            'app/Hosts/Protocol/ContainedPlanFields.php' => $this->containedPlanFieldsClass(),
            ...$go->sources(),
            ...new PhpProtocolSources($this->protocol)->sources(),
            'programs/runner/hookadapter/arguments_gen.go' => $this->hookadapterGo(),
        ];
    }

    private function instructionTypeEnum(): string
    {
        $cases = $this->enumCases($this->protocol->instructionTypes());
        $endsProcess = $this->caseList(fn (HostInstructionTraitsData $instruction) => $instruction->endsProcess, 8);
        $input = $this->caseList(fn (HostInstructionTraitsData $instruction) => $instruction->isInput, 8);

        $notOfferedAgain = $this->caseList(
            fn (HostInstructionTraitsData $instruction) => ! $instruction->isOfferedAgainAfterRestart(),
            8,
        );

        $opening = $this->caseList(fn (HostInstructionTraitsData $instruction) => $instruction->opens, 8);
        $terminal = $this->caseList(fn (HostInstructionTraitsData $instruction) => $instruction->processType === 'terminal', 12);
        $pipe = $this->caseList(fn (HostInstructionTraitsData $instruction) => $instruction->processType === 'pipe', 12);
        $replies = $this->replyArms();
        $payloads = $this->payloadArms();
        $generated = self::GENERATED;
        $source = self::PROTOCOL_FILE;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\Hosts\Protocol;

            use App\Attributes\Generation\AutoGenerated;

            /**
             * Every instruction of host protocol 1, the whole vocabulary a host carries out.
             * {$generated}
             */
            #[AutoGenerated('{$source}')]
            enum HostInstructionType: string
            {
            {$cases}

                /**
                 * Whether the instruction ends its process, so a process that ended still lets its host answer it.
                 */
                public function endsProcess(): bool
                {
                    return in_array(\$this, [{$endsProcess}], true);
                }

                public function isInput(): bool
                {
                    return in_array(\$this, [{$input}], true);
                }

                /**
                 * Whether a claim of this instruction cut off by the host's restart is offered to the new process:
                 * never an input, which is never written twice, nor an instruction the journal gives anew after a
                 * restart.
                 */
                public function isOfferedAgainAfterRestart(): bool
                {
                    return ! in_array(\$this, [{$notOfferedAgain}], true);
                }

                /**
                 * Whether this instruction opens a process, so its payload carries the process's environment.
                 */
                public function isOpening(): bool
                {
                    return in_array(\$this, [{$opening}], true);
                }

                /**
                 * Whether this instruction can be carried out on a process of that type: keys and screens need a terminal,
                 * standard input needs pipes.
                 */
                public function suits(HostProcessType \$type): bool
                {
                    return match (true) {
                        in_array(\$this, [{$terminal}], true) => \$type === HostProcessType::Terminal,
                        in_array(\$this, [{$pipe}], true) => \$type === HostProcessType::Pipe,
                        default => true,
                    };
                }

                /**
                 * The Data of the payload this instruction carries.
                 *
                 * @return class-string<\\Spatie\\LaravelData\\Data>
                 */
                public function payloadOf(): string
                {
                    return match (\$this) {
            {$payloads}
                    };
                }

                /**
                 * The Data a done answer of this instruction carries as its facts.
                 *
                 * @return class-string<\\Spatie\\LaravelData\\Data>
                 */
                public function replyPayload(): string
                {
                    return match (\$this) {
            {$replies}
                    };
                }
            }

            PHP;
    }

    private function refusalEnum(): string
    {
        $refusals = array_map(strval(...), array_keys($this->protocol->refusals));
        $cases = $this->enumCases($refusals);
        $answerFields = $this->phpList($this->protocol->refusedAnswerNames);
        $generated = self::GENERATED;
        $source = self::PROTOCOL_FILE;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\Hosts\Protocol;

            use App\Attributes\Generation\AutoGenerated;

            /**
             * Why a host did not carry out an instruction.
             * {$generated}
             */
            #[AutoGenerated('{$source}')]
            enum HostRefusal: string
            {
            {$cases}

                /**
                 * The fields a refused answer names, so the journal can say why the host refused.
                 */
                public const array ANSWER_FIELDS = [{$answerFields}];
            }

            PHP;
    }

    private function versionClass(): string
    {
        return $this->constantsClass('HostProtocolVersion', 'The version of the host protocol both sides speak.', <<<PHP
                public const int CURRENT = {$this->protocol->version};
            PHP);
    }

    private function placeholdersClass(): string
    {
        $hostNames = $this->phpList($this->protocol->hostNames);

        return $this->constantsClass('HostPlaceholders', 'The placeholders of a plan the host fills itself.', <<<PHP
                /**
                 * The names the host fills as {host:NAME} in a plan.
                 */
                public const array HOST_FILLED = [{$hostNames}];
            PHP);
    }

    private function containedPlanFieldsClass(): string
    {
        $refusedFields = $this->phpList($this->protocol->containedPlan->refusedFields);
        $grantEnvironment = implode("\n", array_map(
            fn (string $name) => "            '{$name}',",
            $this->protocol->containedPlan->startGrantEnvironment,
        ));

        return $this->constantsClass('ContainedPlanFields', 'What a contained plan may and must name.', <<<PHP
                /**
                 * The plan fields a contained plan may not name, as it names nothing of the host it runs on.
                 */
                public const array REFUSED = [{$refusedFields}];

                /**
                 * The variables of a contained program's start grant: a contained plan carries all of them or none.
                 */
                public const array START_GRANT_ENVIRONMENT = [
            {$grantEnvironment}
                ];
            PHP);
    }

    /**
     * A generated class of constants, under its one line of what it holds.
     */
    private function constantsClass(string $name, string $about, string $body): string
    {
        $generated = self::GENERATED;
        $source = self::PROTOCOL_FILE;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\Hosts\Protocol;

            use App\Attributes\Generation\AutoGenerated;

            /**
             * {$about}
             * {$generated}
             */
            #[AutoGenerated('{$source}')]
            final readonly class {$name}
            {
            {$body}
            }

            PHP;
    }

    /**
     * The arms of HostInstructionType::replyPayload: the cases of each reply type on one arm, under the match.
     */
    private function replyArms(): string
    {
        $php = new PhpProtocolSources($this->protocol);
        $cases = [];

        foreach ($this->protocol->instructions as $type => $traits) {
            $cases[$traits->reply][] = 'self::'.Str::studly($type);
        }

        return implode("\n", array_map(
            fn (string $reply, array $instructions) => $this->replyArm($instructions, "Payloads\\{$php->dataName($reply)}::class"),
            array_keys($cases),
            $cases,
        ));
    }

    /**
     * The arms of HostInstructionType::payloadOf: the cases of each payload type on one arm, under the match.
     */
    private function payloadArms(): string
    {
        $php = new PhpProtocolSources($this->protocol);
        $cases = [];

        foreach ($this->protocol->instructions as $type => $traits) {
            $cases[$traits->payload ?? 'empty'][] = 'self::'.Str::studly($type);
        }

        return implode("\n", array_map(
            fn (string $payload, array $instructions) => $this->replyArm($instructions, "Payloads\\{$php->dataName($payload)}::class"),
            array_keys($cases),
            $cases,
        ));
    }

    /**
     * One arm of a match: its cases on one line, or one to a line when they do not fit in 120 characters.
     *
     * @param  list<string>  $cases
     */
    private function replyArm(array $cases, string $answer): string
    {
        $arm = '            '.implode(', ', $cases)." => {$answer},";

        if (strlen($arm) <= 120) {
            return $arm;
        }

        return implode(",\n", array_map(fn (string $case) => "            {$case}", $cases))." => {$answer},";
    }

    private function hookadapterGo(): string
    {
        $arguments = $this->goList($this->protocol->hook()->arguments);

        return <<<GO
            // Code generated by php artisan journal:host-protocol from protocol/host.json. DO NOT EDIT.

            package hookadapter

            // Arguments are what journal-hook takes after its own name, in order.
            var Arguments = []string{{$arguments}}

            GO;
    }

    /**
     * The enum cases, as self::Case, of the instruction types whose traits pass the test: one to a line inside an array
     * opened on a line indented by that many spaces, as Pint keeps it whatever its length.
     *
     * @param  callable(HostInstructionTraitsData): bool  $test
     */
    private function caseList(callable $test, int $indent): string
    {
        $types = array_filter(
            $this->protocol->instructionTypes(),
            fn (string $type) => $test($this->protocol->instructions[$type]),
        );

        $cases = array_map(fn (string $type) => str_repeat(' ', $indent + 4).'self::'.Str::studly($type).",\n", $types);

        return "\n".implode('', $cases).str_repeat(' ', $indent);
    }

    /**
     * The PHP enum cases of the values, each named in PHP's case.
     *
     * @param  list<string>  $values
     */
    private function enumCases(array $values): string
    {
        return $this->lines($values, fn (string $value) => '    case '.Str::studly($value)." = '{$value}';");
    }

    /**
     * @param  list<string>  $items
     * @param  callable(string): string  $line
     */
    private function lines(array $items, callable $line): string
    {
        return implode("\n", array_map($line, $items));
    }

    /**
     * @param  list<string>  $items
     */
    private function phpList(array $items): string
    {
        return implode(', ', array_map(fn (string $item) => "'{$item}'", $items));
    }

    /**
     * @param  list<string>  $items
     */
    private function goList(array $items): string
    {
        return implode(', ', array_map(fn (string $item) => "\"{$item}\"", $items));
    }
}
