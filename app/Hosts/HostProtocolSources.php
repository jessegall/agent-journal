<?php

declare(strict_types=1);

namespace App\Hosts;

use App\Hosts\Data\HostOrderTraitsData;
use App\Hosts\Data\HostProtocolData;
use Illuminate\Support\Str;

/**
 * The Go and PHP source of host protocol 1, rendered from protocol/host.json, by each file's path from the project
 * root; journal:host-protocol writes them, and its check fails when one differs.
 */
final readonly class HostProtocolSources
{
    public const string PROTOCOL_FILE = 'protocol/host.json';

    private const string GENERATED = 'Generated by php artisan journal:host-protocol from protocol/host.json; '
        .'do not edit.';

    public function __construct(private HostProtocolData $protocol) {}

    /**
     * @return array<string, string>
     */
    public function sources(): array
    {
        $go = new GoProtocolSources($this->protocol);

        return [
            'app/Hosts/Protocol/HostOrderType.php' => $this->orderTypeEnum(),
            'app/Hosts/Protocol/HostRefusal.php' => $this->refusalEnum(),
            'app/Hosts/Protocol/HostProtocol.php' => $this->protocolClass(),
            ...$go->sources(),
            'programs/agent/bootstrap/program_streams_gen_test.go' => $go->initStreamsTest(),
            ...new PhpProtocolSources($this->protocol)->sources(),
            'programs/agent/release/host_names_gen.go' => $this->releaseGo(),
            'programs/agent/hookadapter/arguments_gen.go' => $this->hookadapterGo(),
        ];
    }

    private function orderTypeEnum(): string
    {
        $cases = $this->enumCases($this->protocol->orderTypes());
        $endsProcess = $this->caseList(fn (HostOrderTraitsData $order) => $order->endsProcess, 8);
        $input = $this->caseList(fn (HostOrderTraitsData $order) => $order->isInput, 8);

        $notOfferedAgain = $this->caseList(
            fn (HostOrderTraitsData $order) => ! $order->isOfferedAgainAfterRestart(),
            8,
        );

        $opening = $this->caseList(fn (HostOrderTraitsData $order) => $order->opens, 8);
        $terminal = $this->caseList(fn (HostOrderTraitsData $order) => $order->processType === 'terminal', 12);
        $pipe = $this->caseList(fn (HostOrderTraitsData $order) => $order->processType === 'pipe', 12);
        $generated = self::GENERATED;
        $source = self::PROTOCOL_FILE;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\Hosts\Protocol;

            use App\Attributes\AutoGenerated;

            /**
             * Every order of host protocol 1, the whole vocabulary a host carries out.
             * {$generated}
             */
            #[AutoGenerated('{$source}')]
            enum HostOrderType: string
            {
            {$cases}

                /**
                 * Whether the order ends its process, so a process that ended still lets its host answer it.
                 */
                public function endsProcess(): bool
                {
                    return in_array(\$this, [{$endsProcess}], true);
                }

                public function isInput(): bool
                {
                    return in_array(\$this, [{$input}], true);
                }

                /**
                 * Whether a claim of this order cut off by the host's restart is offered to the new process:
                 * never an input, which is never written twice, nor an order the journal gives anew after a
                 * restart.
                 */
                public function isOfferedAgainAfterRestart(): bool
                {
                    return ! in_array(\$this, [{$notOfferedAgain}], true);
                }

                /**
                 * Whether this order opens a process, so its payload carries the process's environment.
                 */
                public function isOpening(): bool
                {
                    return in_array(\$this, [{$opening}], true);
                }

                /**
                 * Whether this order can be carried out on a process of that type: keys and screens need a terminal,
                 * standard input needs pipes.
                 */
                public function suits(HostProcessType \$type): bool
                {
                    return match (true) {
                        in_array(\$this, [{$terminal}], true) => \$type === HostProcessType::Terminal,
                        in_array(\$this, [{$pipe}], true) => \$type === HostProcessType::Pipe,
                        default => true,
                    };
                }
            }

            PHP;
    }

    private function refusalEnum(): string
    {
        $refusals = array_map(strval(...), array_keys($this->protocol->refusals));
        $cases = $this->enumCases($refusals);
        $generated = self::GENERATED;
        $source = self::PROTOCOL_FILE;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\Hosts\Protocol;

            use App\Attributes\AutoGenerated;

            /**
             * Why a host did not carry out an order.
             * {$generated}
             */
            #[AutoGenerated('{$source}')]
            enum HostRefusal: string
            {
            {$cases}
            }

            PHP;
    }

    private function protocolClass(): string
    {
        $version = $this->protocol->version;
        $hostNames = $this->phpList($this->protocol->hostNames);
        $refusedFields = $this->phpList($this->protocol->containedPlan->refusedFields);

        $grantEnvironment = implode("\n", array_map(
            fn (string $name) => "                    '{$name}',",
            $this->protocol->containedPlan->startGrantEnvironment,
        ));

        $hookArguments = $this->phpList($this->protocol->hook()->arguments);
        $generated = self::GENERATED;
        $source = self::PROTOCOL_FILE;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\Hosts\Protocol;

            use App\Attributes\AutoGenerated;

            /**
             * The fixed values of host protocol 1 that the Go host holds too.
             * {$generated}
             */
            #[AutoGenerated('{$source}')]
            final readonly class HostProtocol
            {
                public const int VERSION = {$version};

                /**
                 * The names the host itself fills as {host:NAME} in a plan.
                 */
                public const array HOST_NAMES = [{$hostNames}];

                /**
                 * The plan fields a contained plan may not name, as it names nothing of the host it runs on.
                 */
                public const array CONTAINED_REFUSED_FIELDS = [{$refusedFields}];

                /**
                 * The variables of a contained program's start grant: a contained plan carries all of them or none.
                 */
                public const array CONTAINED_START_GRANT_ENVIRONMENT = [
            {$grantEnvironment}
                ];

                /**
                 * What journal-hook takes after its own name, in order.
                 */
                public const array HOOK_ARGUMENTS = [{$hookArguments}];
            }

            PHP;
    }

    private function releaseGo(): string
    {
        $hostNames = $this->goList($this->protocol->hostNames);

        return <<<GO
            // Code generated by php artisan journal:host-protocol from protocol/host.json. DO NOT EDIT.

            package release

            // reservedHostNames are the names the host itself fills in a plan, which no program may take.
            var reservedHostNames = []string{{$hostNames}}

            GO;
    }

    private function hookadapterGo(): string
    {
        $arguments = $this->goList($this->protocol->hook()->arguments);

        return <<<GO
            // Code generated by php artisan journal:host-protocol from protocol/host.json. DO NOT EDIT.

            package hookadapter

            // Arguments are what journal-hook takes after its own name, in order.
            var Arguments = []string{{$arguments}}

            GO;
    }

    /**
     * The enum cases, as self::Case, of the order types whose traits pass the test: one to a line inside an array
     * opened on a line indented by that many spaces, as Pint keeps it whatever its length.
     *
     * @param  callable(HostOrderTraitsData): bool  $test
     */
    private function caseList(callable $test, int $indent): string
    {
        $types = array_filter(
            $this->protocol->orderTypes(),
            fn (string $type) => $test($this->protocol->orders[$type]),
        );

        $cases = array_map(fn (string $type) => str_repeat(' ', $indent + 4).'self::'.Str::studly($type).",\n", $types);

        return "\n".implode('', $cases).str_repeat(' ', $indent);
    }

    /**
     * The PHP enum cases of the values, each named in PHP's case.
     *
     * @param  list<string>  $values
     */
    private function enumCases(array $values): string
    {
        return $this->lines($values, fn (string $value) => '    case '.Str::studly($value)." = '{$value}';");
    }

    /**
     * @param  list<string>  $items
     * @param  callable(string): string  $line
     */
    private function lines(array $items, callable $line): string
    {
        return implode("\n", array_map($line, $items));
    }

    /**
     * @param  list<string>  $items
     */
    private function phpList(array $items): string
    {
        return implode(', ', array_map(fn (string $item) => "'{$item}'", $items));
    }

    /**
     * @param  list<string>  $items
     */
    private function goList(array $items): string
    {
        return implode(', ', array_map(fn (string $item) => "\"{$item}\"", $items));
    }
}
