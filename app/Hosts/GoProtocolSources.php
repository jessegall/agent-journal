<?php

declare(strict_types=1);

namespace App\Hosts;

use App\Hosts\Data\HostCallData;
use App\Hosts\Data\HostProtocolData;
use App\Hosts\Exceptions\HostFieldTypeUnknown;
use App\Hosts\Values\HostFieldType;
use Illuminate\Support\Str;

/**
 * The Go source of host protocol 1 in each package that holds part of it, laid out as gofmt lays it out: a struct with
 * a Validate for every type and the enums of the package, and in hostapi the protocol's constants, the OrderHandlers
 * interface, the strict dispatch Executors and the typed Journal client.
 */
final readonly class GoProtocolSources
{
    /**
     * Each package the generated Go lives in, by the folder it is written to.
     */
    private const array PACKAGES = [
        'hostapi' => 'programs/agent/hostapi',
        'host' => 'programs/agent/host',
        'client' => 'programs/agent/client',
    ];

    /**
     * The words Go spells in a way of their own: its initialisms, and a name it keeps as written.
     */
    private const array WORDS = [
        'id' => 'ID',
        'url' => 'URL',
        'cpu' => 'CPU',
        'json' => 'JSON',
        'http' => 'HTTP',
        'apparmor' => 'AppArmor',
    ];

    /**
     * The Go type of each scalar of the file.
     */
    private const array SCALARS = [
        'string' => 'string',
        'bool' => 'bool',
        'int' => 'int',
        'int64' => 'int64',
        'uint16' => 'uint16',
        'uint64' => 'uint64',
        'bytes' => '[]byte',
        'time' => 'time.Time',
        'any' => 'any',
    ];

    /**
     * The packages a generated file may import, by the name its code uses them under, the standard ones first.
     */
    private const array IMPORTS = [
        'context' => 'context',
        'fmt' => 'fmt',
        'url' => 'net/url',
        'slices' => 'slices',
        'strconv' => 'strconv',
        'time' => 'time',
        'client' => 'journal-agent/client',
        'host' => 'journal-agent/host',
    ];

    private const string HEADER = '// Code generated by php artisan journal:host-protocol from protocol/host.json. '
        .'DO NOT EDIT.';

    public function __construct(private HostProtocolData $protocol) {}

    /**
     * @return array<string, string> each file's source, by its path from the project root
     */
    public function sources(): array
    {
        $sources = [];

        foreach (self::PACKAGES as $package => $folder) {
            $sources["{$folder}/protocol_gen.go"] = $this->packageSource($package);
        }

        return $sources;
    }

    private function packageSource(string $package): string
    {
        $parts = [];

        if ($package === 'hostapi') {
            $parts[] = $this->constants();
        }

        foreach ($this->protocol->enums as $enum => $values) {
            if ($this->protocol->goPackageOf($enum) === $package) {
                $parts[] = $this->enum($this->goName($enum), Str::studly(Str::beforeLast($enum, '_type')), $values);
            }
        }

        $types = array_filter(
            $this->protocol->types,
            fn (string $type) => $this->protocol->goPackageOf($type) === $package,
            ARRAY_FILTER_USE_KEY,
        );

        foreach ($types as $type => $fields) {
            $parts[] = $this->struct($type, $fields, $package);
            $parts[] = $this->validate($type, $fields);
        }

        if ($package === 'hostapi') {
            $parts[] = $this->handlers();
            $parts[] = $this->executors();
            $parts[] = $this->journal();
        }

        $body = implode("\n\n", $parts);
        $header = self::HEADER;

        return "{$header}\n\npackage {$package}\n\n{$this->imports($body)}{$body}\n";
    }

    /**
     * The import block of what the body uses, the standard packages first, then the host's own, as gofmt groups them.
     */
    private function imports(string $body): string
    {
        $standard = [];
        $own = [];

        foreach (self::IMPORTS as $name => $path) {
            if (preg_match('/(?<![\w.])'.$name.'\.[A-Za-z]/', $body) !== 1) {
                continue;
            }

            if (str_starts_with($path, 'journal-agent/')) {
                $own[] = "\t\"{$path}\"";

                continue;
            }

            $standard[] = "\t\"{$path}\"";
        }

        $groups = array_filter([implode("\n", $standard), implode("\n", $own)]);

        if ($groups === []) {
            return '';
        }

        return "import (\n".implode("\n\n", $groups)."\n)\n\n";
    }

    private function constants(): string
    {
        $version = $this->protocol->version;
        $statuses = $this->enum('Status', '', array_map(strval(...), array_keys($this->protocol->statuses)));
        $refusals = $this->enum('Refusal', '', array_map(strval(...), array_keys($this->protocol->refusals)));
        $keyWidth = max(0, ...array_map(fn (string $type) => strlen($type) + 3, $this->protocol->orderTypes()));

        $traits = implode("\n", array_map(fn (string $type) => sprintf(
            "\t%s {HostWide: %s, Repeatable: %s},",
            str_pad("\"{$type}\":", $keyWidth),
            $this->goBool($this->protocol->orders[$type]->isHostWide()),
            $this->goBool($this->protocol->orders[$type]->isRepeatable),
        ), $this->protocol->orderTypes()));

        $bounds = $this->boundConstants();
        $hostFlags = $this->hostFlags();
        $hostNames = $this->goList($this->protocol->hostNames);
        $refusedFields = $this->goList($this->protocol->containedPlan->refusedFields);
        $grantEnvironment = $this->goList($this->protocol->containedPlan->startGrantEnvironment);

        return <<<GO
            // Protocol is the version of the host protocol this binary speaks.
            const Protocol = {$version}
            {$bounds}

            {$statuses}

            {$refusals}

            // OrderTraits are what the protocol says of an order type: whether it is about the host as a whole, and
            // whether it leaves the same result when carried out twice.
            type OrderTraits struct {
            	HostWide   bool
            	Repeatable bool
            }

            // OrderTypes are every order type of the protocol with its traits.
            var OrderTypes = map[string]OrderTraits{
            {$traits}
            }

            // HostNames are the names the host itself fills as {host:NAME} in a plan.
            var HostNames = []string{{$hostNames}}

            // ContainedRefusedFields are the plan fields a contained plan may not name.
            var ContainedRefusedFields = []string{{$refusedFields}}

            // HostCommandFlags are the flags of each command an installation runs the host program with.
            var HostCommandFlags = map[string][]string{
            {$hostFlags}
            }

            // ContainedStartGrantEnvironment are the variables of a contained program's start grant, which a contained
            // plan carries whole or not at all.
            var ContainedStartGrantEnvironment = []string{{$grantEnvironment}}
            GO;
    }

    /**
     * The host program's commands, one Go map entry to a line, each with its flags.
     */
    private function hostFlags(): string
    {
        $commands = $this->protocol->programs['journal-agent']->commands;

        $names = array_map(strval(...), array_keys($commands));
        $keyWidth = max(0, ...array_map(fn (string $command) => strlen($command) + 3, $names));

        return implode("\n", array_map(
            fn (string $command, array $flags) => "\t".str_pad("\"{$command}\":", $keyWidth)
                ." {{$this->goList($flags)}},",
            $names,
            $commands,
        ));
    }

    /**
     * The test beside the agent image's init that holds it to what the file says of the program's streams.
     */
    public function initStreamsTest(): string
    {
        $prints = $this->goBool($this->protocol->programs['journal-init']->printsOnProgramStreams);
        $header = self::HEADER;

        return <<<GO
            {$header}

            //go:build linux

            package bootstrap

            import (
            	"io"
            	"os"
            	"strings"
            	"testing"
            	"time"

            	"journal-agent/executor"
            )

            // The init prints on the program's streams only as protocol/host.json says: what the executor prints beside
            // its ready line reaches neither the program's stdout nor its stderr.
            func TestTheInitPrintsOnTheProgramsStreamsOnlyAsTheProtocolSays(t *testing.T) {
            	read, write, err := os.Pipe()
            	if err != nil {
            		t.Fatal(err)
            	}
            	stdout, stderr := captured(t, &os.Stdout), captured(t, &os.Stderr)
            	go func() {
            		_, _ = io.WriteString(write, executor.ReadyLine+"\\nthe executor's own line\\n")
            		_ = write.Close()
            	}()
            	if err := waitForExecutor(Layout{SocketWait: 5 * time.Second}, read); err != nil {
            		t.Fatal(err)
            	}
            	time.Sleep(100 * time.Millisecond)

            	printed := stdout() + stderr()
            	if {$prints} != (strings.TrimSpace(printed) != "") {
            		t.Fatalf("the init printed %q on the program's streams", printed)
            	}
            }

            // captured swaps the stream for a pipe until the test ends, and answers what was written to it so far.
            func captured(t *testing.T, stream **os.File) func() string {
            	read, write, err := os.Pipe()
            	if err != nil {
            		t.Fatal(err)
            	}
            	original := *stream
            	*stream = write
            	t.Cleanup(func() { *stream = original })

            	return func() string {
            		*stream = original
            		_ = write.Close()
            		written, _ := io.ReadAll(read)
            		return string(written)
            	}
            }

            GO;
    }

    /**
     * The most each bounded query field of a call takes, a constant to each, each after a blank line.
     */
    private function boundConstants(): string
    {
        $lines = [];

        foreach ($this->protocol->calls as $name => $call) {
            foreach ($call->queryBounds as $field => [$least, $most]) {
                $constant = $this->goName($field === 'limit' ? "{$name}_limit" : "{$name}_{$field}_limit");
                $lines[] = "\n// {$constant} is the most {$field} a {$name} call takes.\nconst {$constant} = {$most}";
            }
        }

        return implode("\n", $lines);
    }

    /**
     * An enum of the protocol as a Go string type: its constants, each named by the prefix and the value, and
     * IsKnown.
     *
     * @param  list<string>  $values
     */
    private function enum(string $name, string $prefix, array $values): string
    {
        $constants = array_map(fn (string $value) => $prefix.Str::studly($value), $values);
        $width = max(0, ...array_map(strlen(...), $constants));

        $lines = implode("\n", array_map(
            fn (string $constant, string $value) => "\t".str_pad($constant, $width)." {$name} = \"{$value}\"",
            $constants,
            $values,
        ));

        $known = implode(', ', $constants);

        return <<<GO
            // {$name} is one of the values host protocol 1 gives it.
            type {$name} string

            const (
            {$lines}
            )

            // IsKnown answers whether the value is one of the protocol's.
            func (value {$name}) IsKnown() bool {
            	return slices.Contains([]{$name}{{$known}}, value)
            }
            GO;
    }

    /**
     * @param  array<string, string>  $fields
     */
    private function struct(string $type, array $fields, string $package): string
    {
        $name = $this->goName($type);
        $names = array_map($this->goName(...), array_keys($fields));
        $types = array_map(fn (string $field) => $this->goType(HostFieldType::parse($field), $package), $fields);
        $nameWidth = max(0, ...array_map(strlen(...), $names));
        $typeWidth = max(0, ...array_values(array_map(strlen(...), $types)));

        $lines = implode("\n", array_map(
            fn (string $field, string $wireName, string $goType) => sprintf(
                "\t%s %s `json:\"%s%s\"`",
                str_pad($field, $nameWidth),
                str_pad($goType, $typeWidth),
                $wireName,
                HostFieldType::parse($fields[$wireName])->isOptional ? ',omitempty' : '',
            ),
            $names,
            array_keys($fields),
            array_values($types),
        ));

        return <<<GO
            // {$name} is the {$type} of host protocol 1.
            type {$name} struct {
            {$lines}
            }
            GO;
    }

    /**
     * The Validate of a type: what its Go types alone do not check, each enum holding one of its values, down every
     * field of a type of the file, the field's path named in what it answers.
     *
     * @param  array<string, string>  $fields
     */
    private function validate(string $type, array $fields): string
    {
        $name = $this->goName($type);
        $checks = '';

        foreach ($fields as $wireName => $field) {
            $checks .= $this->check(HostFieldType::parse($field), 'value.'.$this->goName($wireName), $wireName);
        }

        return <<<GO
            // Validate answers which value of the {$name} the protocol does not know, by its field.
            func (value {$name}) Validate() error {
            {$checks}	return nil
            }
            GO;
    }

    /**
     * The lines, one tab in, that check one field's value; none for a value its Go type already holds to the
     * protocol.
     */
    private function check(HostFieldType $type, string $value, string $path): string
    {
        if ($type->isCollection()) {
            return $this->collectionCheck($type, $value, $path);
        }

        if ($this->isEnum($type->name)) {
            return $this->indented($this->enumCheck($type, $value, $path))."\n";
        }

        if (array_key_exists($type->name, self::SCALARS)) {
            return '';
        }

        $nested = "if err := {$value}.Validate(); err != nil {\n\treturn fmt.Errorf(\"{$path}.%w\", err)\n}";

        if ($type->isNullable) {
            $nested = "if {$value} != nil {\n{$this->indented($nested)}\n}";
        }

        return $this->indented($nested)."\n";
    }

    private function collectionCheck(HostFieldType $type, string $value, string $path): string
    {
        $item = HostFieldType::parse($this->itemText($type));
        $key = $type->isMap ? 'key' : 'index';
        $at = $type->isMap ? "{$path}[%s]" : "{$path}[%d]";

        $check = match (true) {
            $this->isEnum($item->name) => "if !item.IsKnown() {\n"
                ."\treturn fmt.Errorf(\"{$at} holds %q, which host protocol 1 does not know\", {$key}, item)\n}",
            array_key_exists($item->name, self::SCALARS), $item->isCollection() => '',
            default => "if err := item.Validate(); err != nil {\n\treturn fmt.Errorf(\"{$at}.%w\", {$key}, err)\n}",
        };

        if ($check === '') {
            return '';
        }

        return $this->indented("for {$key}, item := range {$value} {\n{$this->indented($check)}\n}")."\n";
    }

    private function enumCheck(HostFieldType $type, string $value, string $path): string
    {
        $read = $type->isNullable ? "*{$value}" : $value;

        $conditions = array_filter([
            $type->isNullable ? "{$value} != nil" : '',
            $type->isOptional && ! $type->isNullable ? "{$value} != \"\"" : '',
            "!{$read}.IsKnown()",
        ]);

        $condition = implode(' && ', $conditions);

        $refusal = "fmt.Errorf(\"{$path} holds %q, which host protocol 1 does not know\", {$read})";

        return "if {$condition} {\n\treturn {$refusal}\n}";
    }

    /**
     * The lines, each one tab further in.
     */
    private function indented(string $lines): string
    {
        return "\t".str_replace("\n", "\n\t", $lines);
    }

    private function handlers(): string
    {
        $methods = implode("\n", array_map(function (string $type) {
            $payload = $this->protocol->orders[$type]->payload;
            $parameter = $payload === null ? '' : ', payload '.$this->goName($payload, 'hostapi');

            return "\t".Str::studly($type)."(ctx context.Context, order Order{$parameter}) (map[string]any, error)";
        }, $this->protocol->orderTypes()));

        return <<<GO
            // OrderHandlers carry out every order of host protocol 1, a method to each order type, given the order and
            // its payload read strictly and validated.
            type OrderHandlers interface {
            {$methods}
            }
            GO;
    }

    private function executors(): string
    {
        $lines = implode("\n", array_map(function (string $type) {
            $carrying = $this->protocol->orders[$type]->payload === null ? 'carryingNothing' : 'carrying';

            return "\texecutors[\"{$type}\"] = {$carrying}(handlers.".Str::studly($type).')';
        }, $this->protocol->orderTypes()));

        return <<<GO
            // Executors carry out each order of host protocol 1 through its handler, its payload read strictly into its
            // type and validated first.
            func Executors(handlers OrderHandlers) map[string]Executor {
            	executors := map[string]Executor{}
            {$lines}
            	return executors
            }
            GO;
    }

    private function journal(): string
    {
        $calls = implode("\n\n", array_map(
            fn (string $call) => $this->call($call, $this->protocol->calls[$call]),
            array_map(strval(...), array_keys($this->protocol->calls)),
        ));

        return <<<GO
            // Journal makes the calls of host protocol 1 to the journal over the host's signed client.
            type Journal struct {
            	Client *client.Client
            }

            {$calls}
            GO;
    }

    private function call(string $name, HostCallData $call): string
    {
        $method = Str::studly($name);
        $parameters = ['ctx context.Context'];

        foreach ($call->pathParts() as $part) {
            $parameters[] = "{$part} string";
        }

        foreach ($call->query as $field => $type) {
            $parameters[] = "{$field} ".self::SCALARS[$type];
        }

        if ($call->body !== null) {
            $parameters[] = 'body '.$this->goName($call->body, 'hostapi');
        }

        $target = $this->target($call->pathPieces(), $call->query);
        $body = $call->body === null ? 'nil' : 'body';
        $signature = implode(', ', $parameters);

        if ($call->reply === null) {
            return <<<GO
                // {$method} makes the {$name} call to {$call->path}.
                func (journal Journal) {$method}({$signature}) error {
                	return journal.Client.Call(ctx, {$target}, {$body}, nil)
                }
                GO;
        }

        $reply = $this->goName($call->reply, 'hostapi');

        return <<<GO
            // {$method} makes the {$name} call to {$call->path} and answers the journal's reply.
            func (journal Journal) {$method}({$signature}) ({$reply}, error) {
            	var reply {$reply}
            	return reply, journal.Client.Call(ctx, {$target}, {$body}, &reply)
            }
            GO;
    }

    /**
     * The Go expression of a call's target: its path's pieces with each part escaped, then its query fields.
     *
     * @param  list<string>  $pathPieces
     * @param  array<string, string>  $query
     */
    private function target(array $pathPieces, array $query): string
    {
        $expression = [];

        foreach ($pathPieces as $index => $piece) {
            if ($index % 2 === 1) {
                $expression[] = "url.PathEscape({$piece})";

                continue;
            }

            if ($piece !== '') {
                $expression[] = "\"{$piece}\"";
            }
        }

        $separator = '?';

        foreach ($query as $field => $type) {
            $expression[] = "\"{$separator}{$field}=\"";
            $expression[] = $type === 'int' ? "strconv.Itoa({$field})" : "url.QueryEscape({$field})";
            $separator = '&';
        }

        return implode('+', $expression);
    }

    /**
     * The Go type of a field, qualified by its package when it lives in another than the one the field is in.
     */
    private function goType(HostFieldType $type, string $package): string
    {
        if ($type->isCollection()) {
            $item = $this->goType(HostFieldType::parse($this->itemText($type)), $package);
            $collection = $type->isMap ? "map[string]{$item}" : "[]{$item}";

            if ($type->isNullable) {
                return "*{$collection}";
            }

            return $collection;
        }

        $named = self::SCALARS[$type->name] ?? $this->goName($type->name, $package);

        if ($type->isNullable) {
            return "*{$named}";
        }

        return $named;
    }

    /**
     * The text of a collection's item type, as the file would write it on its own.
     */
    private function itemText(HostFieldType $type): string
    {
        $item = $type->item ?? throw HostFieldTypeUnknown::of($type->name);

        return $item->name.($item->isNullable ? '|null' : '');
    }

    /**
     * A name of the file as Go spells it, qualified by its package when a package other than the one given holds it.
     */
    private function goName(string $name, string|null $from = null): string
    {
        $words = preg_split('/_|-|(?<=[a-z0-9])(?=[A-Z])/', $name) ?: [];

        $spelled = implode('', array_map(
            fn (string $word) => self::WORDS[strtolower($word)] ?? ucfirst($word),
            $words,
        ));

        if ($from === null) {
            return $spelled;
        }

        $owner = $this->ownerOf($name);

        if ($owner === $from) {
            return $spelled;
        }

        return "{$owner}.{$spelled}";
    }

    /**
     * The package that holds a name of the file, refusing a name the file does not declare.
     */
    private function ownerOf(string $name): string
    {
        $isDeclared = array_key_exists($name, $this->protocol->types) || $this->isEnum($name);

        if (! $isDeclared) {
            throw HostFieldTypeUnknown::of($name);
        }

        if (in_array($name, ['status', 'refusal'], true)) {
            return 'hostapi';
        }

        return $this->protocol->goPackageOf($name);
    }

    private function isEnum(string $name): bool
    {
        return in_array($name, ['status', 'refusal'], true) || array_key_exists($name, $this->protocol->enums);
    }

    /**
     * @param  list<string>  $items
     */
    private function goList(array $items): string
    {
        return implode(', ', array_map(fn (string $item) => "\"{$item}\"", $items));
    }

    private function goBool(bool $value): string
    {
        if ($value) {
            return 'true';
        }

        return 'false';
    }
}
