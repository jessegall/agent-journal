<?php

declare(strict_types=1);

namespace App\Hosts;

use App\Hosts\Data\HostProtocolData;
use App\Hosts\Exceptions\HostFieldTypeUnknown;
use App\Hosts\Values\HostFieldType;
use Illuminate\Support\Str;

/**
 * The Go source of host protocol 1 in each package that holds part of it, laid out as gofmt lays it out: a struct with
 * a Validate for every type and the enums of the package, and in hostapi the protocol's constants, the InstructionHandlers
 * interface, the strict dispatch Executors and the typed Journal client.
 */
final readonly class GoProtocolSources
{
    /**
     * Each package the generated Go lives in, by the folder it is written to.
     */
    private const array PACKAGES = [
        'hostapi' => 'programs/runner/hostapi',
        'host' => 'programs/runner/host',
        'client' => 'programs/runner/client',
    ];

    /**
     * The words Go spells in a way of their own: its initialisms, and a name it keeps as written.
     */
    private const array WORDS = [
        'id' => 'ID',
        'url' => 'URL',
        'cpu' => 'CPU',
        'json' => 'JSON',
        'http' => 'HTTP',
        'apparmor' => 'AppArmor',
    ];

    /**
     * The Go type of each scalar of the file.
     */
    private const array SCALARS = [
        'string' => 'string',
        'bool' => 'bool',
        'int' => 'int',
        'int64' => 'int64',
        'uint16' => 'uint16',
        'uint64' => 'uint64',
        'bytes' => '[]byte',
        'time' => 'time.Time',
        'any' => 'any',
    ];

    /**
     * The packages a generated file may import, by the name its code uses them under, the standard ones first.
     */
    private const array IMPORTS = [
        'context' => 'context',
        'fmt' => 'fmt',
        'url' => 'net/url',
        'slices' => 'slices',
        'strconv' => 'strconv',
        'time' => 'time',
        'client' => 'journal-runner/client',
        'host' => 'journal-runner/host',
    ];

    private const string HEADER = '// Code generated by php artisan journal:host-protocol from protocol/host.json. '
        .'DO NOT EDIT.';

    public function __construct(private HostProtocolData $protocol) {}

    /**
     * @return array<string, string> each file's source, by its path from the project root
     */
    public function sources(): array
    {
        $sources = [];

        foreach (self::PACKAGES as $package => $folder) {
            $sources["{$folder}/protocol_gen.go"] = $this->packageSource($package);
        }

        return $sources;
    }

    private function packageSource(string $package): string
    {
        $parts = [];

        if ($package === 'hostapi') {
            $parts[] = $this->constants();
        }

        foreach ($this->protocol->enums as $enum => $values) {
            if ($this->protocol->goPackageOf($enum) === $package) {
                $parts[] = $this->enum($this->goName($enum), Str::studly(Str::beforeLast($enum, '_type')), $values);
            }
        }

        $types = array_filter(
            $this->protocol->types,
            fn (string $type) => $this->protocol->goPackageOf($type) === $package,
            ARRAY_FILTER_USE_KEY,
        );

        foreach ($types as $type => $fields) {
            $parts[] = $this->struct($type, $fields, $package);
        }

        $body = implode("\n\n", $parts);
        $header = self::HEADER;

        return "{$header}\n\npackage {$package}\n\n{$this->imports($body)}{$body}\n";
    }

    /**
     * The import block of what the body uses, the standard packages first, then the host's own, as gofmt groups them.
     */
    private function imports(string $body): string
    {
        $standard = [];
        $own = [];

        foreach (self::IMPORTS as $name => $path) {
            if (preg_match('/(?<![\w.])'.$name.'\.[A-Za-z]/', $body) !== 1) {
                continue;
            }

            if (str_starts_with($path, 'journal-runner/')) {
                $own[] = "\t\"{$path}\"";

                continue;
            }

            $standard[] = "\t\"{$path}\"";
        }

        $groups = array_filter([implode("\n", $standard), implode("\n", $own)]);

        if ($groups === []) {
            return '';
        }

        return "import (\n".implode("\n\n", $groups)."\n)\n\n";
    }

    private function constants(): string
    {
        $version = $this->protocol->version;
        $statuses = $this->enum('Status', '', array_map(strval(...), array_keys($this->protocol->statuses)));
        $refusals = $this->enum('Refusal', '', array_map(strval(...), array_keys($this->protocol->refusals)));
        $keyWidth = max(0, ...array_map(fn (string $type) => strlen($type) + 3, $this->protocol->instructionTypes()));

        $traits = implode("\n", array_map(fn (string $type) => sprintf(
            "\t%s {HostWide: %s, Repeatable: %s, Opens: %s},",
            str_pad("\"{$type}\":", $keyWidth),
            $this->goBool($this->protocol->instructions[$type]->isHostWide()),
            $this->goBool($this->protocol->instructions[$type]->isRepeatable),
            $this->goBool($this->protocol->instructions[$type]->opens),
        ), $this->protocol->instructionTypes()));

        return <<<GO
            // ProtocolVersion is the version of the host protocol this binary speaks.
            const ProtocolVersion = {$version}

            {$statuses}

            {$refusals}

            // InstructionTraits are what the protocol says of an instruction type: whether it is about the host as a whole, and
            // whether it can be repeated and whether it opens a process.
            type InstructionTraits struct {
            	HostWide   bool
            	Repeatable bool
            	Opens      bool
            }

            // InstructionTypes are every instruction type of the protocol with its traits.
            var InstructionTypes = map[string]InstructionTraits{
            {$traits}
            }
            GO;
    }

    /**
     * An enum of the protocol as a Go string type: its constants, each named by the prefix and the value, and
     * IsKnown.
     *
     * @param  list<string>  $values
     */
    private function enum(string $name, string $prefix, array $values): string
    {
        $constants = array_map(fn (string $value) => $prefix.Str::studly($value), $values);
        $width = max(0, ...array_map(strlen(...), $constants));

        $lines = implode("\n", array_map(
            fn (string $constant, string $value) => "\t".str_pad($constant, $width)." {$name} = \"{$value}\"",
            $constants,
            $values,
        ));

        $known = implode(', ', $constants);

        return <<<GO
            // {$name} is one of the values host protocol 1 gives it.
            type {$name} string

            const (
            {$lines}
            )

            // IsKnown answers whether the value is one of the protocol's.
            func (value {$name}) IsKnown() bool {
            	return slices.Contains([]{$name}{{$known}}, value)
            }
            GO;
    }

    /**
     * @param  array<string, string>  $fields
     */
    private function struct(string $type, array $fields, string $package): string
    {
        $name = $this->goName($type);

        if ($fields === []) {
            return "// {$name} is the {$type} of host protocol 1.\ntype {$name} struct{}";
        }

        $names = array_map($this->goName(...), array_keys($fields));
        $types = array_map(fn (string $field) => $this->goType(HostFieldType::parse($field), $package), $fields);
        $nameWidth = max([0, ...array_map(strlen(...), $names)]);
        $typeWidth = max([0, ...array_values(array_map(strlen(...), $types))]);

        $lines = implode("\n", array_map(
            fn (string $field, string $wireName, string $goType) => sprintf(
                "\t%s %s `json:\"%s%s\"`",
                str_pad($field, $nameWidth),
                str_pad($goType, $typeWidth),
                $wireName,
                HostFieldType::parse($fields[$wireName])->isOptional ? ',omitempty' : '',
            ),
            $names,
            array_keys($fields),
            array_values($types),
        ));

        return <<<GO
            // {$name} is the {$type} of host protocol 1.
            type {$name} struct {
            {$lines}
            }
            GO;
    }

    /**
     * The Go type of a field, qualified by its package when it lives in another than the one the field is in.
     */
    private function goType(HostFieldType $type, string $package): string
    {
        if ($type->isCollection()) {
            $item = $this->goType(HostFieldType::parse($this->itemText($type)), $package);
            $collection = $type->isMap ? "map[string]{$item}" : "[]{$item}";

            if ($type->isNullable) {
                return "*{$collection}";
            }

            return $collection;
        }

        $named = self::SCALARS[$type->name] ?? $this->goName($type->name, $package);

        if ($type->isNullable) {
            return "*{$named}";
        }

        return $named;
    }

    /**
     * The text of a collection's item type, as the file would write it on its own.
     */
    private function itemText(HostFieldType $type): string
    {
        $item = $type->item ?? throw HostFieldTypeUnknown::of($type->name);

        return $item->name.($item->isNullable ? '|null' : '');
    }

    /**
     * A name of the file as Go spells it, qualified by its package when a package other than the one given holds it.
     */
    private function goName(string $name, string|null $from = null): string
    {
        $words = preg_split('/_|-|(?<=[a-z0-9])(?=[A-Z])/', $name) ?: [];

        $spelled = implode('', array_map(
            fn (string $word) => self::WORDS[strtolower($word)] ?? ucfirst($word),
            $words,
        ));

        if ($from === null) {
            return $spelled;
        }

        $owner = $this->ownerOf($name);

        if ($owner === $from) {
            return $spelled;
        }

        return "{$owner}.{$spelled}";
    }

    /**
     * The package that holds a name of the file, refusing a name the file does not declare.
     */
    private function ownerOf(string $name): string
    {
        $isDeclared = array_key_exists($name, $this->protocol->types) || $this->isEnum($name);

        if (! $isDeclared) {
            throw HostFieldTypeUnknown::of($name);
        }

        if (in_array($name, ['status', 'refusal'], true)) {
            return 'hostapi';
        }

        return $this->protocol->goPackageOf($name);
    }

    private function isEnum(string $name): bool
    {
        return in_array($name, ['status', 'refusal'], true) || array_key_exists($name, $this->protocol->enums);
    }

    private function goBool(bool $value): string
    {
        if ($value) {
            return 'true';
        }

        return 'false';
    }
}
