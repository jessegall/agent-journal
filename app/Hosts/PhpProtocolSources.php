<?php

declare(strict_types=1);

namespace App\Hosts;

use App\Hosts\Data\HostCallData;
use App\Hosts\Data\HostInstructionTraitsData;
use App\Hosts\Data\HostProtocolData;
use App\Hosts\Exceptions\HostFieldTypeUnknown;
use App\Hosts\Values\HostFieldType;
use Illuminate\Support\Str;

/**
 * The PHP source of host protocol 1 beside its instruction types: a Data class with its validation for every type, the
 * enums, HostInstructions that places each instruction with its typed payload, the HostCalls the journal answers the host's calls
 * with, a controller for each call that reads and validates its request, and the routes of the calls.
 */
final readonly class PhpProtocolSources
{
    private const string FOLDER = 'app/Hosts/Protocol';

    private const string PROTOCOL_NAMESPACE = 'App\\Hosts\\Protocol';

    private const string GENERATED = 'Generated by php artisan journal:host-protocol from protocol/host.json; '
        .'do not edit.';

    /**
     * The PHP type of each scalar of the file.
     */
    private const array SCALARS = [
        'string' => 'string',
        'bool' => 'bool',
        'int' => 'int',
        'int64' => 'int',
        'uint16' => 'int',
        'uint64' => 'int',
        'bytes' => 'string',
        'time' => 'string',
        'any' => 'mixed',
    ];

    /**
     * The value a number, yes or no, or list left out of a call reads as, as Go leaves out a field holding it; a text
     * left out reads as null.
     */
    private const array ZEROS = [
        'bool' => 'false',
        'int' => '0',
        'array' => '[]',
    ];

    /**
     * The enum each of the file's own enums is, by its name in the file.
     */
    private const array ENUMS = [
        'status' => 'HostAnswerStatus',
        'refusal' => 'HostRefusal',
    ];

    public function __construct(private HostProtocolData $protocol) {}

    /**
     * @return array<string, string> each file's source, by its path from the project root
     */
    public function sources(): array
    {
        $sources = [];
        $statuses = array_map(strval(...), array_keys($this->protocol->statuses));
        $sources[self::FOLDER.'/HostAnswerStatus.php'] = $this->enum('HostAnswerStatus', 'status', $statuses);

        foreach ($this->protocol->enums as $enum => $values) {
            $name = $this->enumName($enum);
            $sources[self::FOLDER."/{$name}.php"] = $this->enum($name, $enum, $values);
        }

        foreach ($this->protocol->wireTypes() as $type => $fields) {
            $sources[self::FOLDER."/Payloads/{$this->dataName($type)}.php"] = $this->data($type, $fields);
        }

        $sources[self::FOLDER.'/HostInstructions.php'] = $this->instructions();
        $sources[self::FOLDER.'/HostProgramLines.php'] = $this->programLines();
        $sources[self::FOLDER.'/HostCalls.php'] = $this->calls();
        $sources[self::FOLDER.'/HostRoute.php'] = $this->routeEnum();

        foreach ($this->protocol->calls as $name => $call) {
            $sources[self::FOLDER.'/Http/'.$this->controllerName($name).'.php'] = $this->controller(
                $name,
                $call,
            );
        }

        $sources['routes/agents/host-protocol.php'] = $this->routes();

        return $sources;
    }

    /**
     * @param  list<string>  $values
     */
    private function enum(string $name, string $source, array $values): string
    {
        $cases = implode("\n", array_map(
            fn (string $value) => '    case '.Str::studly($value)." = '{$value}';",
            $values,
        ));

        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace};

            use App\\Attributes\\Generation\\AutoGenerated;

            /**
             * The {$source} values of host protocol 1.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            enum {$name}: string
            {
            {$cases}
            }

            PHP;
    }

    /**
     * A type's Data class: each field a promoted property named in PHP's case, mapped to its wire name when that
     * differs, typed and validated as the file says, a field that may be left out given the value Go leaves out.
     *
     * @param  array<string, string>  $fields
     */
    private function data(string $type, array $fields): string
    {
        $required = [];
        $optional = [];
        $documented = [];

        foreach ($fields as $wireName => $text) {
            $field = HostFieldType::parse($text);
            $property = $this->property((string) $wireName, $field);

            if ($field->isOptional) {
                $optional[] = $property;
            } else {
                $required[] = $property;
            }

            if ($field->isCollection()) {
                $name = $this->propertyName((string) $wireName, $field);
                $documented[] = "     * @param  {$this->docType($field)}  \${$name}";
            }
        }

        $properties = implode("\n", [...$required, ...$optional]);

        $constructor = $properties === ''
            ? '    public function __construct() {}'
            : "    public function __construct(\n{$properties}\n    ) {}";

        $docblock = $documented === [] ? '' : "    /**\n".implode("\n", $documented)."\n     */\n";
        $name = $this->dataName($type);
        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;
        $enums = $this->enumImports();

        $version = array_key_exists($type, $this->protocol->types)
            ? $this->protocol->version
            : $this->protocol->relayVersion();

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace}\\Payloads;

            use App\\Attributes\\Generation\\AutoGenerated;
            use App\\Attributes\\Validation\\ValidationOnRead;
            use App\\Attributes\\Validation\\OptionalField;
            use Spatie\\LaravelData\\Attributes\\Validation\\Present;
            {$enums}
            use Spatie\\LaravelData\\Attributes\\DataCollectionOf;
            use Spatie\\LaravelData\\Attributes\\MapName;
            use Spatie\\LaravelData\\Attributes\\Validation\\Date;
            use Spatie\\LaravelData\\Attributes\\Validation\\Max;
            use Spatie\\LaravelData\\Attributes\\Validation\\Min;
            use Spatie\\LaravelData\\Data;

            /**
             * The {$type} of host protocol {$version}.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            #[ValidationOnRead]
            final class {$name} extends Data
            {
            {$docblock}{$constructor}
            }

            PHP;
    }

    /**
     * One promoted property of a Data class, with its attributes on the line above it.
     */
    private function property(string $wireName, HostFieldType $field): string
    {
        $name = $this->propertyName($wireName, $field);
        $attributes = [];

        if ($name !== $wireName) {
            $attributes[] = "#[MapName('{$wireName}')]";
        }

        if ($field->isCollection() && $this->isDataName($this->itemOf($field)->name)) {
            $attributes[] = '#[DataCollectionOf('.$this->dataName($this->itemOf($field)->name).'::class)]';
        }

        if ($field->isOptional) {
            $attributes[] = '#[OptionalField]';
        } elseif (! $field->isNullable) {
            $attributes[] = '#[Present]';
        }

        $attributes = [
            ...$attributes,
            ...$this->rulesOf($field),
        ];

        $phpType = $this->phpType($field);
        $isNullable = $field->isNullable || ($field->isOptional && ! array_key_exists($phpType, self::ZEROS));
        $declared = $isNullable && $phpType !== 'mixed' ? "{$phpType}|null" : $phpType;
        $default = '';

        if ($field->isOptional) {
            $default = ' = '.($isNullable ? 'null' : self::ZEROS[$phpType]);
        }

        $lines = array_map(fn (string $attribute) => "        {$attribute}", $attributes);
        $lines[] = "        public readonly {$declared} \${$name}{$default},";

        return implode("\n", $lines);
    }

    /**
     * A field's property name in PHP's case; a yes or no whose wire name does not read as a question is named with is.
     */
    private function propertyName(string $wireName, HostFieldType $field): string
    {
        $isQuestion = preg_match('/^(is|has|can|as)(_|[A-Z])/', $wireName) === 1;

        if ($field->name === 'bool' && ! $isQuestion) {
            return 'is'.Str::studly($wireName);
        }

        return Str::camel($wireName);
    }

    /**
     * The validation attributes the file's scalar names add to its PHP type.
     *
     * @return list<string>
     */
    private function rulesOf(HostFieldType $field): array
    {
        return match ($field->isCollection() ? '' : $field->name) {
            'uint16' => [
                '#[Min(0)]',
                '#[Max(65535)]',
            ],
            'uint64' => ['#[Min(0)]'],
            'time' => ['#[Date]'],
            default => [],
        };
    }

    private function phpType(HostFieldType $field): string
    {
        if ($field->isCollection()) {
            return 'array';
        }

        if ($this->isScalar($field->name)) {
            return self::SCALARS[$field->name];
        }

        if ($this->isEnum($field->name)) {
            return $this->enumName($field->name);
        }

        return $this->dataName($field->name);
    }

    /**
     * The type a collection's docblock gives it: a list or a map of string keys, of its item's PHP type.
     */
    private function docType(HostFieldType $field): string
    {
        $item = $this->itemOf($field);
        $itemType = $item->isCollection() ? $this->docType($item) : $this->phpType($item);

        if ($field->isMap) {
            return "array<string, {$itemType}>";
        }

        return "list<{$itemType}>";
    }

    private function instructions(): string
    {
        $methods = [];

        foreach ($this->protocol->instructionTypes() as $type) {
            $traits = $this->protocol->instructions[$type];

            // An opening's payload is its plan's, placed by HostInstructionPlacement::forOpening with the process it opens.
            if ($traits->opens) {
                continue;
            }

            $method = Str::camel($type);
            $case = Str::studly($type);
            $payload = $traits->payload === null ? '' : ', '.$this->dataName($traits->payload).' $payload';
            $array = $traits->payload === null ? '[]' : '$payload->toArray()';

            if ($traits->isHostWide()) {
                $methods[] = <<<PHP
                        /**
                         * Places the {$type} instruction on the host.
                         *
                         * @throws HostProtocolRefused
                         */
                        public function {$method}(string \$hostId, HostInstructionSource \$source{$payload}): HostInstruction
                        {
                            return \$this->placement->forHost(\$hostId, \$source, HostInstructionType::{$case}, {$array});
                        }
                    PHP;

                continue;
            }

            $methods[] = <<<PHP
                    /**
                     * Places the {$type} instruction on the process, to be carried out within the seconds.
                     *
                     * @throws HostProtocolRefused
                     * @throws WorkerFenced
                     */
                    public function {$method}(
                        string \$processId,
                        HostInstructionSource \$source{$payload},
                        int \$expirySeconds = HostInstructionPlacement::INSTRUCTION_SECONDS,
                    ): HostInstruction {
                        return \$this->placement->forProcess(
                            \$processId,
                            \$source,
                            HostInstructionType::{$case},
                            {$array},
                            \$expirySeconds,
                        );
                    }
                PHP;
        }

        $body = implode("\n\n", $methods);
        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;

        $imports = implode("\n", array_map(
            fn (string $type) => "use {$namespace}\\Payloads\\{$this->dataName($type)};",
            array_values(array_unique(array_filter(array_map(
                fn (HostInstructionTraitsData $traits) => $traits->opens ? null : $traits->payload,
                $this->protocol->instructions,
            )))),
        ));

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace};

            use App\\Attributes\\Generation\\AutoGenerated;
            use App\\Exceptions\\HostProtocolRefused;
            use App\\Exceptions\\WorkerFenced;
            use App\\Hosts\\HostInstructionPlacement;
            use App\\Models\\Hosts\\HostInstruction;
            use App\\Values\\HostInstructionSource;
            {$imports}

            /**
             * Places every instruction of host protocol 1 but an opening, a method to each, with its typed payload.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            final readonly class HostInstructions
            {
                public function __construct(private HostInstructionPlacement \$placement) {}

            {$body}
            }

            PHP;
    }

    /**
     * The command lines of the drivers the journal runs, by their executable, as the file declares them.
     */
    private function programLines(): string
    {
        $lines = [];

        foreach ($this->protocol->programs as $name => $program) {
            if ($program->executable === null) {
                continue;
            }

            $lines[] = "        '{$program->executable}' => [\n            'program' => '{$name}',\n"
                ."            'words' => {$this->phpMap($program->words, '            ')},\n"
                ."            'options' => {$this->phpMap($program->options, '            ')},\n"
                .'            \'takes_prompt\' => '.($program->takesPrompt ? 'true' : 'false').",\n        ],";
        }

        $body = implode("\n", $lines);
        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;

        $hookArguments = implode(', ', array_map(fn (string $argument) => "'{$argument}'", $this->protocol->hook()->arguments));

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace};

            use App\\Attributes\\Generation\\AutoGenerated;

            /**
             * The drivers' command lines host protocol 1 declares: each word and option, and the values it takes.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            final readonly class HostProgramLines
            {
                /**
                 * Each driver's line by its executable: its program, words and options, and whether a prompt ends it.
                 */
                public const array LINES = [
            {$body}
                ];

                /**
                 * What journal-hook takes after its own name, in order.
                 */
                public const array HOOK_ARGUMENTS = [{$hookArguments}];
            }

            PHP;
    }

    /**
     * A map of names to the values they take as PHP source, one entry to a line under the indent.
     *
     * @param  array<string, string>  $map
     */
    private function phpMap(array $map, string $indent): string
    {
        $entries = array_map(
            fn (string $key, string $value) => "{$indent}    '{$key}' => HostArgumentValues::".Str::studly($value).',',
            array_map(strval(...), array_keys($map)),
            $map,
        );

        return "[\n".implode("\n", $entries)."\n{$indent}]";
    }

    private function calls(): string
    {
        $methods = [];
        $imports = [];

        foreach ($this->protocol->calls as $name => $call) {
            $reply = $call->reply === null ? 'void' : $this->dataName($call->reply);
            $parameters = implode(', ', $this->callParameters($call));

            $methods[] = <<<PHP
                    /**
                     * Answers the host's {$name} call to {$call->path}.
                     */
                    public function {$this->methodName($name)}({$parameters}): {$reply};
                PHP;

            $imports = [
                ...$imports,
                ...array_filter([$call->body, $call->reply]),
            ];
        }

        $body = implode("\n\n", $methods);
        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;

        $uses = implode("\n", array_map(
            fn (string $type) => "use {$namespace}\\Payloads\\{$this->dataName($type)};",
            array_values(array_unique($imports)),
        ));

        $constants = $this->boundConstants();

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace};

            use App\\Attributes\\Generation\\AutoGenerated;
            use App\\Hosts\\Values\\HostContext;
            {$uses}

            /**
             * What the journal answers each call of host protocol 1 with, its body read and validated first.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            interface HostCalls
            {
            {$constants}{$body}
            }

            PHP;
    }

    /**
     * Every call of the protocol as an enum, each able to say whether a path is one of its own.
     */
    private function routeEnum(): string
    {
        $cases = [];
        $patterns = [];
        $bodies = [];
        $replies = [];

        foreach ($this->protocol->calls as $name => $call) {
            $case = Str::studly($name);
            $cases[] = "    case {$case} = '{$name}';";
            $bodies[] = "            self::{$case} => Payloads\\{$this->dataName($call->body ?? 'empty')}::class,";
            $replies[] = "            self::{$case} => Payloads\\{$this->dataName($call->reply ?? 'empty')}::class,";
            $pattern = '#^'.preg_replace('/\\\\\{\\w+\\\\\}/', '[^/]+', preg_quote($call->path, '#')).'$#';
            $patterns[] = "            self::{$case} => '{$pattern}',";
        }

        $caseLines = implode("\n", $cases);
        $patternLines = implode("\n", $patterns);
        $bodyLines = implode("\n", $bodies);
        $replyLines = implode("\n", $replies);
        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace};

            use App\\Attributes\\Generation\\AutoGenerated;

            /**
             * Every call the host makes to the journal in host protocol 1, by its name.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            enum HostRoute: string
            {
            {$caseLines}

                /**
                 * Whether the path, without its query, is this call's.
                 */
                public function matchesPath(string \$path): bool
                {
                    return preg_match(match (\$this) {
            {$patternLines}
                    }, \$path) === 1;
                }

                /**
                 * The Data of the body the host sends with this call.
                 *
                 * @return class-string<\\Spatie\\LaravelData\\Data>
                 */
                public function bodyPayload(): string
                {
                    return match (\$this) {
            {$bodyLines}
                    };
                }

                /**
                 * The Data of the journal's answer to this call.
                 *
                 * @return class-string<\\Spatie\\LaravelData\\Data>
                 */
                public function replyPayload(): string
                {
                    return match (\$this) {
            {$replyLines}
                    };
                }
            }

            PHP;
    }

    /**
     * @return list<string>
     */
    private function callParameters(HostCallData $call): array
    {
        $parameters = ['HostContext $host'];

        foreach ($call->pathParts() as $part) {
            $parameters[] = "string \${$part}";
        }

        foreach ($call->query as $field => $type) {
            $parameters[] = self::SCALARS[$type]." \${$field}";
        }

        if ($call->body !== null) {
            $parameters[] = $this->dataName($call->body).' $body';
        }

        return $parameters;
    }

    /**
     * A call's controller: it reads the call's query and body strictly into their types, answering 422 with every
     * field the protocol does not take, and hands them to HostCalls.
     */
    private function controller(string $name, HostCallData $call): string
    {
        $controller = $this->controllerName($name);
        $method = $this->methodName($name);
        $isReadingRequest = $call->query !== [] || $call->body !== null;

        $parameters = $isReadingRequest ? [
            'Request $request',
            'HostContext $host',
            'HostCalls $calls',
        ] : [
            'HostContext $host',
            'HostCalls $calls',
        ];

        if ($call->body !== null) {
            $parameters[] = 'HostCallReader $reader';
        }

        $arguments = ['$host'];

        foreach ($call->pathParts() as $part) {
            $parameters[] = "string \${$part}";
            $arguments[] = "\${$part}";
        }

        $lines = [];

        if ($call->query !== []) {
            $rules = implode("\n", array_map(
                fn (string $field) => "            '{$field}' => {$this->queryRules($call, $field)},",
                array_map(strval(...), array_keys($call->query)),
            ));

            $lines[] = "        \$request->validate([\n{$rules}\n        ]);";

            foreach (array_keys($call->query) as $field) {
                $arguments[] = "\$request->integer('{$field}')";
            }
        }

        $uses = [];

        if ($call->body !== null) {
            $data = $this->dataName($call->body);
            $uses[] = "use App\\Hosts\\Protocol\\Payloads\\{$data};";

            $lines[] = $call->bodyByteLimit === null
                ? "        \$body = \$reader->read(\$request->getContent(), {$data}::class, '{$name}');"
                : <<<PHP
                            \$body = \$reader->readAtMost(
                                \$request->getContent(),
                                {$call->bodyByteLimit},
                                {$data}::class,
                                '{$name}',
                            );
                    PHP;

            $arguments[] = '$body';
        }

        $invocation = "\$calls->{$method}(".implode(', ', $arguments).')';

        if ($call->reply === null) {
            $lines[] = "        {$invocation};";
            $lines[] = '';
            $lines[] = '        return new Response(status: Response::HTTP_NO_CONTENT);';
            $answer = 'Response';
        } else {
            $lines[] = "        return new JsonResponse({$invocation});";
            $answer = 'JsonResponse';
        }

        $signature = implode("\n", array_map(fn (string $parameter) => "        {$parameter},", $parameters));
        $body = implode("\n", $lines);
        $imports = implode("\n", $uses);
        $namespace = self::PROTOCOL_NAMESPACE;
        $generated = self::GENERATED;
        $path = $call->path;

        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace}\\Http;

            use App\\Attributes\\Generation\\AutoGenerated;
            use App\\Hosts\\HostCallReader;
            use App\\Hosts\\Protocol\\HostCalls;
            use App\\Hosts\\Values\\HostContext;
            use Illuminate\\Http\\JsonResponse;
            use Illuminate\\Http\\Request;
            use Illuminate\\Http\\Response;
            {$imports}

            /**
             * The host's {$name} call to {$path}.
             * {$generated}
             */
            #[AutoGenerated('protocol/host.json')]
            final readonly class {$controller}
            {
                public function __invoke(
            {$signature}
                ): {$answer} {
            {$body}
                }
            }

            PHP;
    }

    private function routes(): string
    {
        $routes = [];
        $imports = [];

        foreach ($this->protocol->calls as $name => $call) {
            $controller = $this->controllerName($name);
            $imports[] = "use App\\Hosts\\Protocol\\Http\\{$controller};";
            $path = Str::after($call->path, '/host');
            $routes[] = "    Route::post('{$path}', {$controller}::class)->name('{$call->route}');";
        }

        $uses = implode("\n", $imports);
        $lines = implode("\n", $routes);
        $generated = self::GENERATED;

        return <<<PHP
            <?php

            declare(strict_types=1);

            // The calls of host protocol 1. {$generated}

            use App\\Projects\\Enums\\HostRouteRole;
            {$uses}
            use Illuminate\\Support\\Facades\\Route;

            Route::prefix('host')
                ->middleware(['journal.host:'.HostRouteRole::Shared->value, 'record.calls:host'])
                ->name('agents.host.')
                ->group(function (): void {
            {$lines}
                });

            PHP;
    }

    /**
     * The validation rules of a query field as PHP source: a whole number, within its bounds when it has them.
     */
    private function queryRules(HostCallData $call, string $field): string
    {
        if (! array_key_exists($field, $call->queryBounds)) {
            return "['required', 'integer']";
        }

        [$least, $most] = $call->queryBounds[$field];

        return "['required', 'integer', 'min:{$least}', 'max:{$most}']";
    }

    /**
     * The constants of HostCalls: the most each bounded query field of a call takes.
     */
    private function boundConstants(): string
    {
        $lines = [];

        foreach ($this->protocol->calls as $name => $call) {
            foreach ($call->queryBounds as $field => [$least, $most]) {
                $constant = Str::upper($field === 'limit' ? "{$name}_limit" : "{$name}_{$field}_limit");

                $lines[] = "    /**\n     * The most {$field} a {$name} call takes.\n     */\n"
                    ."    public const int {$constant} = {$most};";
            }
        }

        if ($lines === []) {
            return '';
        }

        return implode("\n\n", $lines)."\n\n";
    }

    private function controllerName(string $call): string
    {
        return Str::studly($call).'Controller';
    }

    private function methodName(string $call): string
    {
        return Str::camel($call);
    }

    /**
     * The Data class of a type of the file, named with Host once.
     */
    public function dataName(string $type): string
    {
        if (! array_key_exists($type, $this->protocol->wireTypes())) {
            throw HostFieldTypeUnknown::of($type);
        }

        $studly = Str::studly($type);

        return (str_starts_with($studly, 'Host') ? $studly : "Host{$studly}").'Payload';
    }

    /**
     * The use lines of every enum of the file, one under another as a Data class's imports list them.
     */
    private function enumImports(): string
    {
        $names = [
            ...array_values(self::ENUMS),
            ...array_map($this->enumName(...), array_keys($this->protocol->enums)),
        ];

        sort($names);

        return implode("\n", array_map(fn (string $name) => 'use '.self::PROTOCOL_NAMESPACE."\\{$name};", $names));
    }

    private function enumName(string $enum): string
    {
        return self::ENUMS[$enum] ?? 'Host'.Str::studly($enum);
    }

    private function isEnum(string $name): bool
    {
        return array_key_exists($name, self::ENUMS) || array_key_exists($name, $this->protocol->enums);
    }

    /**
     * Whether the name is one of the file's types, which a Data class holds, rather than a scalar or an enum.
     */
    private function isDataName(string $name): bool
    {
        return ! $this->isScalar($name) && ! $this->isEnum($name);
    }

    private function isScalar(string $name): bool
    {
        return array_key_exists($name, self::SCALARS);
    }

    private function itemOf(HostFieldType $field): HostFieldType
    {
        return $field->item ?? throw HostFieldTypeUnknown::of($field->name);
    }
}
