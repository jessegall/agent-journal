<?php

declare(strict_types=1);

namespace App\AgentRequests\Support;

use App\AgentRequests\Contracts\JournalCall;
use App\AgentRequests\Exceptions\EndpointDeclarationInvalid;
use App\Files\Support\CodeFiles;
use App\Reflection\Support\DeclaredType;
use App\Reflection\Support\ReflectedMethod;
use App\Reflection\Support\ReflectedParameter;
use App\Reflection\Support\Reflector;
use Illuminate\Support\Str;
use UnitEnum;

/**
 * Writes the call groups of the signed calls: one group per Calls folder, holding one method per call that builds
 * the call and sends it, and the JournalClient root holding Core's groups.
 */
final class CallGroups
{
    /**
     * The group of one Calls folder as PHP source, or null when the folder declares no call.
     *
     * @throws EndpointDeclarationInvalid
     */
    public static function group(string $folder, string $namespace, string $area): string|null
    {
        $calls = self::callsIn($folder, $namespace);

        if ($calls === []) {
            return null;
        }

        $methods = implode("\n", array_map(self::method(...), $calls));
        $group = self::groupName($area);

        return <<<PHP
        <?php

        declare(strict_types=1);

        namespace {$namespace};

        use App\\AgentRequests\\Contracts\\CallSender;
        use App\\AgentRequests\\Support\\CallKey;

        /**
         * The signed calls of {$area}, generated by php artisan journal:calls; run it again instead of editing.
         */
        final readonly class {$group}
        {
            public function __construct(private CallSender \$sender) {}
        {$methods}}

        PHP;
    }

    /**
     * The JournalClient root over Core's groups, as PHP source.
     *
     * @param  array<string, class-string>  $groups  each Core area's group class, by area
     */
    public static function client(array $groups): string
    {
        $properties = implode('', array_map(
            fn (string $area, string $class) => "\n        public \\{$class} \$".Str::camel($area).',',
            array_keys($groups),
            $groups,
        ));
        $constructor = $groups === [] ? '' : <<<TEXT

            public function __construct({$properties}
            ) {}

        TEXT;

        return <<<PHP
        <?php

        declare(strict_types=1);

        namespace App\\Client\\Support;

        /**
         * Every Core group of signed calls, generated by php artisan journal:calls; run it again instead of editing.
         */
        final readonly class JournalClient
        {{$constructor}}

        PHP;
    }

    public static function groupName(string $area): string
    {
        return Str::singular($area).'Calls';
    }

    /**
     * @return list<class-string>
     */
    private static function callsIn(string $folder, string $namespace): array
    {
        $calls = [];

        $code = CodeFiles::ofProcess();

        foreach ($code->folder($code->projectPathOf("{$folder}/*Call.php")) as $entry) {
            $class = $namespace.'\\'.basename($entry->name(), '.php');

            if (Reflector::factory()->isSubclassOf($class, JournalCall::class)) {
                $calls[] = $class;
            }
        }

        sort($calls);

        return $calls;
    }

    /**
     * @param  class-string  $call
     *
     * @throws EndpointDeclarationInvalid
     */
    private static function method(string $call): string
    {
        $endpoint = CallDeclaration::of($call)->endpoint;
        $declaration = Reflector::of($call);
        $name = lcfirst(Str::beforeLast($declaration->shortName(), 'Call'));
        $parameters = $declaration->constructor()
            ->map(fn (ReflectedMethod $constructor) => $constructor->parameters())
            ->getOrElse([]);
        $signature = implode('', array_map(
            fn (ReflectedParameter $parameter) => "\n        ".self::parameter($parameter).',',
            $parameters,
        ));
        $parameterAssignments = implode('', array_map(
            fn (ReflectedParameter $parameter) => <<<TEXT

                        '{$parameter->name()}' => \${$parameter->name()},
            TEXT,
            $parameters,
        ));
        $answer = '\\'.$endpoint->answer;
        $docblock = self::docblock($declaration);

        return <<<PHP

        {$docblock}    public function {$name}({$signature}
            ): {$answer} {
                return \$this->sender->send(\\{$call}::from([{$parameterAssignments}
                ]));
            }

        PHP;
    }

    private static function parameter(ReflectedParameter $parameter): string
    {
        $declared = $parameter->type()->filter(fn (DeclaredType $type) => $type->isNamed());

        if ($declared->isEmpty()) {
            return "mixed \${$parameter->name()}";
        }

        $type = $declared->get();
        $nullable = $type->allowsNull && $type->name() !== 'mixed' ? '?' : '';
        $leading = $type->isBuiltin() ? '' : '\\';
        $written = $nullable.$leading.$type->name();
        $default = $type->name() === CallKey::class ? ' = new CallKey()' : self::defaultOf($parameter);

        return "{$written} \${$parameter->name()}{$default}";
    }

    /**
     * The default a call's constructor gives the parameter, written as source; none when it has none.
     */
    private static function defaultOf(ReflectedParameter $parameter): string
    {
        if (! $parameter->hasDefaultValue()) {
            return '';
        }

        $constant = $parameter->defaultConstantName();

        if ($constant->isDefined()) {
            return ' = \\'.ltrim($constant->get(), '\\');
        }

        $defaultArgument = $parameter->defaultValue();

        return match (true) {
            $defaultArgument instanceof UnitEnum => ' = \\'.$defaultArgument::class.'::'.$defaultArgument->name,
            is_object($defaultArgument) => ' = new \\'.$defaultArgument::class.'()',
            default => ' = '.str_replace(["array (\n)", 'NULL'], ['[]', 'null'], var_export($defaultArgument, true)),
        };
    }

    /**
     * The array shapes the call's constructor documents, so the group method types its arrays as the call does; a
     * class named in a shape is written in full, since the group file does not share the call's imports.
     *
     * @param  Reflector<object>  $call
     */
    private static function docblock(Reflector $call): string
    {
        $documented = $call->constructor()->flatMap(fn (ReflectedMethod $constructor) => $constructor->docComment());

        if ($documented->isEmpty()) {
            return '';
        }

        $constructorDoc = $documented->get();

        preg_match_all('/@param\s+(.+?)\s+(\$\w+)\s*$/m', $constructorDoc, $params, PREG_SET_ORDER);

        if ($params === []) {
            return '';
        }

        $imports = self::importsOf($call);
        $lines = array_map(
            fn (array $param) => '     * @param  '.self::fullyNamed($param[1], $imports, $call)."  {$param[2]}\n",
            $params,
        );

        return "/**\n".implode('', $lines)."     */\n";
    }

    /**
     * The classes the call's file imports, by the short name it uses for each.
     *
     * @param  Reflector<object>  $call
     * @return array<string, string>
     */
    private static function importsOf(Reflector $call): array
    {
        $code = CodeFiles::ofProcess();
        preg_match_all(
            '/^use\s+([\w\\\\]+)(?:\s+as\s+(\w+))?;/m',
            $code->file($code->projectPathOf($call->fileName()->getOrElse(''))),
            $uses,
            PREG_SET_ORDER,
        );
        $imports = [];

        foreach ($uses as $use) {
            $imports[$use[2] ?? class_basename($use[1])] = $use[1];
        }

        return $imports;
    }

    /**
     * The type with every class name in it written in full: an imported name by its import, any other by the
     * call's own namespace.
     *
     * @param  array<string, string>  $imports
     * @param  Reflector<object>  $call
     */
    private static function fullyNamed(string $type, array $imports, Reflector $call): string
    {
        return (string) preg_replace_callback(
            '/(?<![\w\\\\])[A-Z]\w*/',
            fn (array $name) => '\\'.($imports[$name[0]] ?? $call->namespaceName().'\\'.$name[0]),
            $type,
        );
    }
}
