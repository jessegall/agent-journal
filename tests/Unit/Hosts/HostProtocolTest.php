<?php

declare(strict_types=1);

namespace Tests\Unit\Hosts;

use App\Agents\Values\RelayedHookCommand;
use App\Attributes\Generation\AutoGenerated;
use App\Files\Contracts\Files;
use App\Files\Enums\Place;
use App\Hosts\Protocol\HostInstructionType;
use App\Hosts\Protocol\HostProgramLines;
use App\Hosts\Protocol\HostProtocolVersion;
use App\Hosts\Protocol\HostRefusal;
use App\Support\Reflector;
use App\Values\FilePath;
use Tests\Support\TimeLimits\TimeLimit;
use Tests\TestCase;

/**
 * The journal's side of host protocol 1 is generated from protocol/host.json and follows it: the generated files are
 * current and name their source, a hand edit of one fails the check, and the hook command the journal writes carries exactly journal-hook's
 * arguments.
 */
#[TimeLimit(seconds: 20, reason: 'The check formats every generated PHP file with Pint.')]
final class HostProtocolTest extends TestCase
{
    public function test_the_generated_files_are_current(): void
    {
        $this->artisan('journal:host-protocol', ['--check' => true])->assertSuccessful();
    }

    public function test_each_generated_type_names_the_protocol_file_it_is_generated_from(): void
    {
        $sources = array_map(
            fn (string $type) => Reflector::of($type)->attribute(AutoGenerated::class)->source,
            [HostInstructionType::class, HostRefusal::class, HostProtocolVersion::class],
        );

        $this->assertSame(array_fill(0, 3, 'protocol/host.json'), $sources);
    }

    public function test_a_hand_edit_of_a_generated_go_file_fails_the_check(): void
    {
        $this->artisan('journal:host-protocol', ['--into' => 'host-protocol-check'])->assertSuccessful();
        $files = $this->app->make(Files::class);
        $copy = FilePath::in(Place::Temporary, 'host-protocol-check/programs/runner/hostapi/protocol_gen.go');
        $files->write($copy, $files->read($copy)."\n// changed by hand\n");

        $this->artisan('journal:host-protocol', ['--check' => true, '--into' => 'host-protocol-check'])
            ->expectsOutputToContain('programs/runner/hostapi/protocol_gen.go differs')
            ->assertFailed();
    }

    public function test_the_hook_command_carries_exactly_the_arguments_journal_hook_takes(): void
    {
        $command = RelayedHookCommand::for('/opt/journal/bin/journal-hook', 'claude-code')->text;

        $this->assertCount(count(HostProgramLines::HOOK_ARGUMENTS), array_slice(explode(' ', $command), 1));
    }
}
