const DOING = [
    [/^journal (message|comment|reaction|question)\b/, "inbox"],
    [/^journal\b/, "journal"],
    [/\b(pytest|python3? (-m )?tests?\/|npm test|vitest|jest|phpunit)\b/, "tests"],
    [/\b(npm run build|vite build|make\b|cargo build|go build|tsc\b)/, "build"],
    [/^git (commit|push|add)\b/, "commit"],
    [/^git\b/, "history"],
    [/^(grep|rg|ag|find|ls|cat|sed -n|head|tail|wc|tree|fd)\b/, "code"],
    [/^(python3?|node|php|ruby|perl|bash|sh)\b/, "script"],
    [/^(curl|wget|http)\b/, "service"],
];

const TOOLS = {
    Read: "reading",
    Edit: "editing",
    MultiEdit: "editing",
    NotebookEdit: "editing",
    Write: "writing",
    Grep: "searching",
    Glob: "searching",
    WebFetch: "web",
    WebSearch: "web",
    Agent: "helper",
    Task: "helper",
    Skill: "skill",
    TodoWrite: "list",
};

export function kindOf(agent) {
    const tool = agent.tool || "";
    if (!agent.tool_running) return "bearings";
    if (!tool || tool === "Bash") return (DOING.find(([pattern]) => pattern.test((agent.doing || "").trim())) || [null, "command"])[1];
    if (tool.startsWith("mcp__")) return /playwright|browser|chrome/.test(tool.slice(5).split("__")[0]) ? "browser" : "service";
    return TOOLS[tool] || "tool";
}

export function busyWording(agent) {
    const wordings = WORDINGS[kindOf(agent)];
    const seed = Math.floor(Date.parse(agent.heard_at || "") / 1000) || 0;
    return wordings[seed % wordings.length];
}

export const wordingsOf = (kind) => WORDINGS[kind];
